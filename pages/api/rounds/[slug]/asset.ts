import type { NextApiRequest, NextApiResponse } from "next";
import { createHash } from "crypto";
import { getPublicRoundImage } from "data/rounds";
import { decodeRoundImageDataUrl, processRoundImage } from "@/utils/rounds/image-processing";
import { imageStorageReadiness, isRoundImageKeyForSubmission, signRoundImage } from "@/utils/rounds/image-storage";
import { normalizeSafeImageUrl } from "@/utils/url-safety";

export const config = { api: { responseLimit: false } };
// Bounded hot-preview cache contains bytes, never authorization decisions.
const previews = new Map<string, Buffer>();
let cachedBytes = 0;
let pending = 0;
let processing: Promise<unknown> = Promise.resolve();
const preview = async (image: string) => {
  const key = createHash("sha256").update(image).digest("hex");
  const cached = previews.get(key);
  if (cached) return cached;
  if (pending >= 32) throw new Error("Media processing busy.");
  pending++;
  const result = processing.then(async () => {
    const cached = previews.get(key);
    if (cached) return cached;
    const { preview } = await processRoundImage(image);
    while (cachedBytes + preview.length > 16 * 1024 * 1024 && previews.size) {
      const first = previews.keys().next().value!;
      cachedBytes -= previews.get(first)!.length;
      previews.delete(first);
    }
    previews.set(key, preview); cachedBytes += preview.length;
    return preview;
  });
  processing = result.catch(() => undefined);
  try { return await result; } finally { pending--; }
};

export default async function handler(req: NextApiRequest, res: NextApiResponse) {
  res.setHeader("Cache-Control", "private, no-store, max-age=0");
  res.setHeader("X-Content-Type-Options", "nosniff");
  if (req.method !== "GET") {
    res.setHeader("Allow", "GET");
    return res.status(405).json({ error: "Method not allowed." });
  }
  const slug = typeof req.query.slug === "string" ? req.query.slug : "";
  const id = req.query.cover === "1" ? null : typeof req.query.id === "string" ? req.query.id : "";
  const index = req.query.cover === "1" ? 0 : Number(req.query.index);
  if (!slug || id === "" || !Number.isInteger(index) || index < 0 || index >= 10 || !["preview", "original"].includes(String(req.query.variant)))
    return res.status(400).json({ error: "Invalid image request." });
  try {
    const storageReady = imageStorageReadiness().ready;
    const record = await getPublicRoundImage(slug, id, index, { includeLegacyBytes: !storageReady });
    if (!record?.image) return res.status(404).json({ error: "Image not found." });
    const asset = record.asset;
    if (asset && storageReady) {
      // Motion is part of GIF artwork, including on the grid. Existing stored
      // still previews remain compatible, but GIF delivery uses unchanged bytes.
      const key = req.query.variant === "preview" && asset.mime !== "image/gif"
        ? asset.previewKey : asset.key;
      if (!isRoundImageKeyForSubmission(key, record.round_id, record.submission_id))
        return res.status(503).json({ error: "Image attachment is unavailable." });
      return res.redirect(302, await signRoundImage(key));
    }
    if (!record.image.startsWith("data:image/")) {
      const url = normalizeSafeImageUrl(record.image, { allowInternal: true });
      if (!url || url.includes("/asset?")) return res.status(404).json({ error: "Image not found." });
      return res.redirect(302, url);
    }
    if (asset) res.setHeader("X-Round-Media-Fallback", "legacy-storage-unavailable");
    // Canonical Noundry SVGs are generated by the server from escaped pixels.
    // Preserve the vector artwork without running a remote-capable SVG parser.
    if (record.source === "noundry" && record.submission_type === "trait" && /^data:image\/svg\+xml;base64,[A-Za-z0-9+/=]+$/.test(record.image)) {
      if (record.image.length > 512 * 1024) return res.status(413).json({ error: "Image exceeds the size limit." });
      res.setHeader("Content-Security-Policy", "sandbox; default-src 'none'; style-src 'unsafe-inline'");
      res.setHeader("Content-Type", "image/svg+xml");
      return res.status(200).send(Buffer.from(record.image.split(",")[1], "base64"));
    }
    if (req.query.variant === "preview" && !record.image.startsWith("data:image/gif;base64,")) {
      res.setHeader("Content-Type", "image/webp");
      return res.status(200).send(await preview(record.image));
    }
    const { original, mime } = decodeRoundImageDataUrl(record.image);
    res.setHeader("Content-Type", mime);
    return res.status(200).send(original);
  } catch {
    // Never log provider errors containing signed query strings or credentials.
    res.setHeader("Retry-After", "5");
    return res.status(503).json({ error: "Image temporarily unavailable. Please retry." });
  }
}
