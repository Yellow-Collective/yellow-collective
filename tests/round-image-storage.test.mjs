const cache = new Map();
function load(file, overrides = {}) {
  file = resolve(file);
  if (cache.has(file)) return cache.get(file);
  const module = { exports: {} };
  const source = ts.transpileModule(readFileSync(file, "utf8"), { compilerOptions: { esModuleInterop: true, module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 } }).outputText;
  const customRequire = (name) => overrides[name] || (name.startsWith(".") ? load(resolve(dirname(file), `${name}.ts`), overrides) : require(name));
  vm.runInNewContext(source, { require: customRequire, module, exports: module.exports, Buffer, process: { env: overrides.__env || {} }, URL, AbortSignal, setTimeout, clearTimeout });
  cache.set(file, module.exports);
  return module.exports;
}
