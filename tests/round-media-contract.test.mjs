import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import vm from 'node:vm';
const require=createRequire(import.meta.url), ts=require('typescript');
const module={exports:{}};
vm.runInNewContext(ts.transpileModule(readFileSync('utils/rounds/roundMediaPayload.ts','utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2020}}).outputText,{module,exports:module.exports,require,URL});
const media=module.exports;
const image='data:image/png;base64,'+'a'.repeat(12000);
const round={id:'r',slug:'fixture',updatedAt:'2026-10-19',image,unexpectedLegacyMedia:image,submissions:[{id:'s',updatedAt:'rev',image,images:[image,image],sourcePayload:{previewTraits:{preview:image},roundSubmissionIdentityLabel:'trait metadata'}}],voteActivity:[]};
const compact=media.createRoundMediaPayload(round,2);
assert.equal(compact.version,2);
assert.equal('submissionImages' in compact,false);
assert.equal(JSON.stringify(compact).includes('data:image'),false);
assert.equal(compact.submissionImageSets.s.length,2);
assert.match(compact.submissionImageSets.s[0],/variant=preview/);
assert.match(compact.submissionImageSets.s[1],/variant=original/);
const stripped=media.stripRoundInlineMediaForSsr(round);
assert.equal(JSON.stringify(stripped).includes('data:image'),false);
assert.equal(stripped.submissions[0].sourcePayload.roundSubmissionIdentityLabel,'trait metadata');
assert.equal('unexpectedLegacyMedia' in stripped,false);
assert.equal(round.submissions[0].sourcePayload.previewTraits.preview,image);
const hydrated=media.hydrateRoundInlineMedia(stripped,compact);
assert.equal(hydrated.submissions[0].images.length,2);
assert.match(hydrated.submissions[0].image,/variant=preview/);
const moderated=media.hydrateRoundInlineMedia(stripped,{...compact,submissionImageSets:{}});
assert.equal(moderated.submissions.length,0);
const summary=media.serializePublicRoundSummary({...round,content:image,description:'Safe summary',sourcePayload:{image}});
assert.equal(JSON.stringify(summary).includes('data:image'),false);
assert.equal('content' in summary,false);
assert.equal('sourcePayload' in summary,false);
assert.equal(summary.description,'Safe summary');
const traitRound={...round,submissions:[...round.submissions,{id:'trait',submissionType:'trait',source:'noundry',sourcePayload:{pixels:[['#ffcc00']],selectedTraits:{head:1}}}]};
const unavailable=media.clearRoundArtwork(traitRound);
assert.equal(unavailable.image,'');
assert.equal(unavailable.submissions.length,0,'failed eligibility refresh removes pixels-derived artwork as well as image URLs');
assert.equal(traitRound.submissions.length,2,'the source domain records remain unchanged');
console.log('ok - compact media removes nested image bytes without mutating domain records and preserves order');
